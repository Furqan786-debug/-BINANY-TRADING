import { Asset, CandleData } from '../types';

function generateCandles(basePrice: number, count: number = 80, intervalSeconds: number = 300, volatility: number = 0.008): CandleData[] {
  const candles: CandleData[] = [];
  const now = Math.floor(Date.now() / 1000);
  let currentPrice = basePrice * (1 - (count * 0.001));

  for (let i = count; i >= 0; i--) {
    const time = now - (i * intervalSeconds);
    const delta = (Math.random() - 0.49) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(0.0001, open + delta);
    const high = Math.max(open, close) + Math.random() * volatility * 0.7 * currentPrice;
    const low = Math.min(open, close) - Math.random() * volatility * 0.7 * currentPrice;
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time,
      open: Number(open.toFixed(4)),
      high: Number(high.toFixed(4)),
      low: Number(low.toFixed(4)),
      close: Number(close.toFixed(4)),
      volume,
    });

    currentPrice = close;
  }

  return candles;
}

